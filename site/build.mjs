import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { render } from './render.mjs';
import { exportBlog, staticArticles, staticCategories } from './export-blog.mjs';

const check = process.argv.includes('--check');
const root = new URL('../', import.meta.url);
const domain = (await readFile(new URL('CNAME', root), 'utf8')).trim();
const origin = `https://${domain}`;
const home = { origin, articles: staticArticles, categories: staticCategories };
const homeCss = (await Promise.all(['site', 'forms', 'tv'].map((name) => readFile(new URL(`assets/${name}.css`, root), 'utf8')))).join('\n');
const files = new Map([['assets/home.css', '/* Generated by npm run build. Edit site.css, forms.css or tv.css. */\n' + homeCss], ['index.html', render('fa', home)], ['en.html', render('en', home)], ...exportBlog(origin)]);
for (const [file, html] of files) {
  const url = new URL(file, root);
  if (!check) {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, html);
  } else if (await readFile(url, 'utf8').catch(() => '') !== html) {
    console.error(`${file} is out of date. Run npm run build.`);
    process.exitCode = 1;
  }
}
